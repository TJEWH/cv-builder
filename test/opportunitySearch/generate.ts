import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { OPPORTUNITY_SEARCH_PROTOCOL, OPPORTUNITY_RESULT_SCHEMA, SEARCH_PROTOCOL_VERSION, SEARCH_BOOTSTRAP_VERSION, buildOpportunitySearchSetupPrompt } from '../../src/composables/opportunitySearchProtocol';
import { sqlText } from '../../src/composables/refinementProtocolContract';
import type { SearchTemplate } from '../../src/searchTypes';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const searchProtocolHash = 'sha256:' + createHash('sha256').update(JSON.stringify({
  text: OPPORTUNITY_SEARCH_PROTOCOL, schema: OPPORTUNITY_RESULT_SCHEMA, bootstrap: SEARCH_BOOTSTRAP_VERSION,
})).digest('hex');
